
package Entite;

public class TypeVacance {
    private int id;
    private String TypeVacance;

    public TypeVacance() {
    }

    public TypeVacance(int id, String TypeVacance) {
        this.id = id;
        this.TypeVacance = TypeVacance;
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getTypeVacance() {
        return TypeVacance;
    }

    public void setTypeVacance(String TypeVacance) {
        this.TypeVacance = TypeVacance;
    }
    
    
    
}
